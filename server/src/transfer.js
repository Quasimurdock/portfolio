/**
 * Database import — move a SQLite file into whichever database this server is
 * configured to use (docs/DENO-PORT.md §9).
 *
 * The case this exists for: the site ran locally on SQLite for a while, then
 * moved to a hosted Postgres, and every article, image row and account had to
 * be retyped. This walks the tables in a safe order and writes them into the
 * current target.
 *
 * Three things make it less trivial than `INSERT … SELECT`:
 *
 *   1. `images.collection_id` and `collections.cover_image_id` point at each
 *      other, so whichever table goes first cannot fill its column. Those two
 *      are inserted as NULL and patched by a second pass.
 *   2. Every `id` is `GENERATED BY DEFAULT AS IDENTITY`, which accepts explicit
 *      ids but leaves the sequence behind them, so the next API-created row
 *      would collide. The sequences are repaired at the end.
 *   3. `sessions` and `audit_logs` are optional: a session cookie from another
 *      install means nothing here, and audit history is often not wanted.
 *   4. Merge inserts explicit ids, so a row whose id, email or slug is already
 *      taken in the target is skipped rather than overwritten (`ON CONFLICT DO
 *      NOTHING`). Content is never lost — the new row simply is not added — but
 *      rows pointing at it keep pointing at whatever was already there, so the
 *      response counts every skipped row and warns.
 *
 * Nothing here ever writes to the file that was uploaded: it is copied to a
 * temp file, opened read-only, and removed again.
 */
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { DatabaseSync } from 'node:sqlite'

import { describeTarget, driverName, exec, get, run, tx } from './db.js'

